class FakeLLM:
    """Scenario-driven fake LLM covering the surface the graph nodes use.

    Routing of :meth:`complete` is by marker text in the prompt, matching the
    real node prompts:

    * ``"CLASSIFICATION"`` -> classify block (``DECISION: SEARCH`` etc.).
    * ``"CONFIDENCE:"`` -> evaluate block that ends the loop after one round.
    * otherwise -> the plan node, which expects a JSON array of query strings.

    :meth:`complete_structured` is the claim extractor's path; it returns the
    caller-supplied ``claims`` payload. :meth:`complete_with_metadata` is the
    answer node's per-section path; it returns scenario-specific markdown.

    The answer markdown is built from a small spec: the fake reads the ``[E#]``
    labels present in the section prompt and, for each requested binding, emits
    a sentence that cites that label and restates the claim text so the real
    binding heuristic (``_claim_plausible_in_segment``) can match it.
    """

    def __init__(
        self,
        *,
        classify_decision: str = "SEARCH",
        classify_language: str = "de",
        classify_search_language: str = "de",
        classify_recency: str = "NONE",
        classify_type: str = "GENERAL",
        sub_questions: list[str] | None = None,
        plan_queries: list[str] | None = None,
        evaluate_confidence: int = 8,
        evaluate_status: str = "SUFFICIENT",
        answer_contract: str = "GENERAL",
        covered_aspects: list[int] | None = None,
        claim_payload: list[dict[str, Any]] | None = None,
        source_roles: list[dict[str, str]] | None = None,
        claim_payloads_by_call: list[list[dict[str, Any]]] | None = None,
        answer_bindings: list[dict[str, str]] | None = None,
        answer_extra_text: str = "",
        answer_override: str | None = None,
    ) -> None:
        """Wire one concrete scenario into the fake LLM.

        Args:
            classify_decision: ``SEARCH`` (research) or ``DIRECT`` (skip
                search). The harness scenarios always research.
            classify_language / classify_search_language: ISO codes echoed in
                the classify block.
            classify_recency: One of ``NONE/HOUR/DAY/WEEK/MONTH``.
            classify_type: One of ``GENERAL/ACADEMIC/NEWS``.
            sub_questions: Decomposed sub-questions; defaults to a single
                generic one so the focus-stem filter stays permissive.
            plan_queries: Query strings the plan node should emit as a JSON
                array. Defaults to two NVIDIA-relevant queries.
            evaluate_confidence: CONFIDENCE value (1-10) for the evaluate
                block. ``8`` matches the default ``confidence_stop``.
            evaluate_status: STATUS token (``SUFFICIENT``/``INSUFFICIENT``).
            source_roles: ``source_roles`` rows (``ref``/``role``/``reason``)
                returned with every structured claim reply; empty by
                default, so every source stays unjudged (unknown) and the
                round emits the 'nicht beurteilt' status line.
            claim_payloads_by_call: Optional per-call claim payloads (the
                last one repeats) for scenarios whose queries must yield
                different evidence snippets.
            claim_payload: The ``claims`` list returned by
                :meth:`complete_structured`. ``None`` -> no claims (an empty
                list), which models a valid-empty extraction.
            answer_bindings: List of ``{"label": "E#", "claim_text": "..."}``
                hints. For each, the answer prose emits one sentence citing
                ``[E#]`` and restating ``claim_text`` so a claim that shares
                that source URL binds as ``matched``. The fake auto-rewrites a
                requested label to one actually present in the prompt when the
                exact label is absent.
            answer_extra_text: Extra prose appended to every section body.
            answer_override: When set, every section returns this exact markdown
                verbatim, ignoring bindings/labels. Models an LLM that writes
                arbitrary prose -- e.g. citation-free body text -- so a scenario
                can exercise an answer that ignores the available evidence.
        """
        self.models = SimpleNamespace(
            reasoning_model="reasoning-model",
            effective_classify_model="classify-model",
            effective_evaluate_model="evaluate-model",
            effective_claim_extract_model="claim-extract-model",
        )
        self._classify_decision = classify_decision
        self._classify_language = classify_language
        self._classify_search_language = classify_search_language
        self._classify_recency = classify_recency
        self._classify_type = classify_type
        self._sub_questions = sub_questions or ["NVIDIA Quartalszahlen"]
        self._plan_queries = plan_queries or [
            "Welche Quartalszahlen hat NVIDIA zuletzt gemeldet?",
            "Wie hoch war der NVIDIA Umsatz im ersten Quartal Geschaeftsjahr 2027?",
        ]
        self._evaluate_confidence = int(evaluate_confidence)
        self._evaluate_status = evaluate_status
        self._answer_contract = answer_contract
        self._covered_aspects = covered_aspects
        self._claim_payload = claim_payload if claim_payload is not None else []
        self._source_roles = source_roles if source_roles is not None else []
        # Optional per-call payloads (the last one repeats): a scenario whose
        # queries must yield DIFFERENT evidence snippets uses this.
        self._claim_payloads_by_call = claim_payloads_by_call
        self._answer_bindings = answer_bindings or []
        self._answer_extra_text = answer_extra_text
        self._answer_override = answer_override

        # Diagnostics the tests can read to confirm routing happened through
        # the real nodes rather than a fake short-circuit.
        self.complete_calls: list[str] = []
        self.structured_calls = 0
        self.answer_section_calls = 0

    # -- capability flags ------------------------------------------------- #
    def is_available(self) -> bool:
        """Report the fake as configured and ready."""
        return True

    def supports_structured_output(self, *, model: str | None = None) -> bool:
        """Advertise native structured output so the claim extractor uses it."""
        return True

    # -- routing helpers -------------------------------------------------- #
    def _classify_block(self) -> str:
        return (
            f"DECISION: {self._classify_decision}\n"
            f"LANGUAGE: {self._classify_language}\n"
            f"SEARCH_LANGUAGE: {self._classify_search_language}\n"
            f"RECENCY: {self._classify_recency}\n"
            f"TYPE: {self._classify_type}\n"
            f"ANSWER_CONTRACT: {self._answer_contract}\n"
            f"SUB_QUESTIONS: {json.dumps(self._sub_questions, ensure_ascii=False)}"
        )

    def _evaluate_block(self) -> str:
        return (
            f"STATUS: {self._evaluate_status}\n"
            f"CONFIDENCE: {self._evaluate_confidence}\n"
            "GAPS: Keine\n"
            "CONTRADICTIONS: Nein\n"
            "COMPETING_EVENTS: Keine\n"
            f"COVERED_ASPECTS: {json.dumps(self._covered_aspects if self._covered_aspects is not None else [1, 2, 3, 4])}\n"
            "EVIDENCE_CONSISTENCY: 9\n"
            "EVIDENCE_SUFFICIENCY: 9"
        )

    def _plan_block(self) -> str:
        return json.dumps(self._plan_queries, ensure_ascii=False)

    # -- LLMProvider surface ---------------------------------------------- #
    def complete(self, prompt: str, **kwargs: Any) -> str:
        """Route a reasoning call by marker text to classify/evaluate/plan."""
        if "CLASSIFICATION" in prompt:
            self.complete_calls.append("classify")
            return self._classify_block()
        if "CONFIDENCE:" in prompt:
            self.complete_calls.append("evaluate")
            return self._evaluate_block()
        self.complete_calls.append("plan")
        return self._plan_block()

    def complete_with_metadata(self, prompt: str, **kwargs: Any) -> LLMResponse:
        """Answer-node path: synthesize scenario markdown for one section.

        The answer node calls this once per report section with the section
        system prompt embedded under ``system=`` and the section task under
        ``prompt=``. The evidence overview (with ``[E#]`` labels) lives in the
        system prompt, so the fake reads labels from BOTH the prompt and the
        system text, then emits binding sentences for the configured labels.
        """
        self.answer_section_calls += 1
        system = str(kwargs.get("system", "") or "")
        available_labels = _EVIDENCE_LABEL_RE.findall(f"{system}\n{prompt}")
        body = self._build_answer_body(available_labels)
        return LLMResponse(
            content=body,
            model="reasoning-model",
            finish_reason="stop",
        )

    def complete_structured(
        self,
        prompt: str,
        *,
        schema: dict[str, Any],
        schema_name: str,
        **kwargs: Any,
    ) -> StructuredLLMResponse:
        """Claim-extractor path: return the scenario's ``claims`` payload."""
        self.structured_calls += 1
        payload = self._claim_payload
        if self._claim_payloads_by_call:
            index = min(self.structured_calls - 1, len(self._claim_payloads_by_call) - 1)
            payload = self._claim_payloads_by_call[index]
        return StructuredLLMResponse(
            parsed={
                "claims": copy.deepcopy(payload),
                "source_roles": copy.deepcopy(self._source_roles),
            },
            content="",
            model="claim-extract-model",
            finish_reason="stop",
            schema_name=schema_name,
        )

    # -- answer synthesis ------------------------------------------------- #
    def _build_answer_body(self, available_labels: list[str]) -> str:
        """Compose section markdown citing configured ``[E#]`` labels.

        For each requested binding, emit one sentence that cites the label and
        restates the claim text. When the requested label is not present in the
        prompt (label assignment is score-dependent and the test cannot predict
        it), fall back to the first available label so the citation is still on
        the allow-list and resolves to a real source.

        When ``answer_override`` was supplied, return it verbatim instead --
        modelling an LLM that writes arbitrary prose (e.g. citation-free body).
        """
        if self._answer_override is not None:
            return self._answer_override

        ordered_unique: list[str] = []
        for label in available_labels:
            if label not in ordered_unique:
                ordered_unique.append(label)

        lines: list[str] = ["## Antwort", ""]
        used_fallback_index = 0
        for binding in self._answer_bindings:
            label = str(binding.get("label", "")).strip()
            claim_text = str(binding.get("claim_text", "")).strip()
            if label not in ordered_unique and ordered_unique:
                label = ordered_unique[used_fallback_index % len(ordered_unique)]
                used_fallback_index += 1
            if not label:
                continue
            # Restating the claim text inside the same sentence as the [E#]
            # citation is what makes the real claim/segment binding `matched`.
            lines.append(f"Laut [{label}] gilt: {claim_text}".rstrip())
            lines.append("")

        if self._answer_extra_text:
            lines.append(self._answer_extra_text)
            lines.append("")

        if len(lines) <= 2:
            # No bindings configured (source-only / source-context scenarios):
            # still produce a short, source-citing body when labels exist so
            # the URL-level audit has something to resolve.
            if ordered_unique:
                lines.append(
                    f"Die vorliegenden Quellen behandeln das Thema [{ordered_unique[0]}]."
                )
            else:
                lines.append(
                    "Zu dieser Frage liegen derzeit keine belegfaehigen Quellen vor."
                )
            lines.append("")

        return "\n".join(lines).rstrip() + "\n"
