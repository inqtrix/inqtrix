"""Fake LLM and search providers for the offline end-to-end harness.

These fakes sit ONLY at the LLM / search I/O boundary. Every graph node,
strategy, consolidation step and contract computation runs the real
``inqtrix`` code; the fakes just feed deterministic provider outputs in.

Design goals:

* :class:`FakeSearch` replays a real captured ``GroundedSearchResult`` (the
  NVIDIA Quartalszahlen fixture) so the source/citation/rank shape that flows
  into the evidence pipeline is the production shape, not a hand-built stub.
* :class:`FakeLLM` is scenario-driven. It routes the four real prompt kinds
  (classify, plan, evaluate, answer) by marker text, and emits structured
  claim-extraction payloads + answer prose that the caller wires per test.
  The answer text is generated by reading the ``[E#]`` evidence labels out of
  the section prompt the real answer node hands it, so a "clean" scenario can
  cite exactly the labels the real graph assigned without the test hard-coding
  them.

The loader mirrors ``tests/fixtures/bedrock_responses.py``: fixtures live as
JSON under ``tests/fixtures/search_results/`` so the protective sanitization
scan discovers them automatically.
"""

from __future__ import annotations

import copy
import json
import pathlib
import re
import threading
from dataclasses import replace
from types import SimpleNamespace
from typing import Any, Sequence

from inqtrix.providers.base import LLMResponse, StructuredLLMResponse
from inqtrix.search_result import GroundedSearchResult, GroundedSource

_FIXTURE_ROOT = pathlib.Path(__file__).resolve().parent / "fixtures" / "search_results"

# Match the [E#] source labels the answer node embeds in the section prompt.
_EVIDENCE_LABEL_RE = re.compile(r"\[(E\d+)\]")


# --------------------------------------------------------------------------- #
# Fixture loader
# --------------------------------------------------------------------------- #


def load_search_result_fixture(slug: str) -> GroundedSearchResult:
    """Hydrate a :class:`GroundedSearchResult` from a captured JSON fixture.

    Args:
        slug: File stem under ``tests/fixtures/search_results/`` without the
            ``.json`` suffix (for example ``"nvidia_quartalszahlen"``). A
            missing file raises :class:`FileNotFoundError` with the resolved
            path so a typo in the test surfaces immediately.

    Returns:
        A :class:`GroundedSearchResult` whose sources preserve the captured
        ``rank`` ordinals — those are what the synthesized answer's inline
        ``[id]`` citations reference and what the claim extractor resolves
        ``provider_refs`` against.

    Notes:
        Top-level and per-source keys beginning with ``_`` (for example the
        ``_capture`` provenance note) are ignored so capture metadata never
        leaks into the typed result.
    """
    path = _FIXTURE_ROOT / f"{slug}.json"
    if not path.exists():
        raise FileNotFoundError(f"Search fixture {slug!r} not found at {path}")
    raw = json.loads(path.read_text(encoding="utf-8"))
    payload = {k: v for k, v in raw.items() if not k.startswith("_")}
    sources = [
        GroundedSource(
            **{k: v for k, v in source.items() if not k.startswith("_")}
        )
        for source in payload.get("sources", [])
    ]
    return GroundedSearchResult(
        answer=payload.get("answer", ""),
        sources=sources,
        related_questions=list(payload.get("related_questions", []) or []),
        prompt_tokens=int(payload.get("prompt_tokens", 0) or 0),
        completion_tokens=int(payload.get("completion_tokens", 0) or 0),
    )


def source_only_result(base: GroundedSearchResult) -> GroundedSearchResult:
    """Return *base* with the synthesized answer stripped but sources kept.

    Models a provider (e.g. a URL-only backend) that returns citable sources
    without prose. Claim extraction yields nothing without answer text, so the
    real graph must ingest these purely as source-context evidence records.
    """
    return GroundedSearchResult(
        answer="",
        sources=list(base.sources),
        related_questions=list(base.related_questions),
        prompt_tokens=base.prompt_tokens,
        completion_tokens=base.completion_tokens,
    )


def subset_result(
    base: GroundedSearchResult,
    ranks: Sequence[int],
    *,
    answer: str | None = None,
) -> GroundedSearchResult:
    """Carve a per-query result out of a captured fixture's real sources.

    Keeps only the sources whose original ``rank`` is in *ranks*, re-ranked
    1..N to mirror how each provider query independently ranks its own hits.
    Source content (real URLs/titles/snippets/dates from the capture) is left
    intact -- only the partition and the ordinal change -- so a multi-query
    scenario combines AUTHENTIC source shapes from distinct queries rather than
    invented stubs.

    Args:
        base: The loaded fixture to slice.
        ranks: Original 1-based ranks to keep, in the order they should appear.
        answer: Optional per-query answer text. ``None`` reuses the fixture's
            answer; pass a short query-specific answer when the inline-citation
            ordinals of the full fixture answer would not match the slice.

    Returns:
        A :class:`GroundedSearchResult` carrying the selected sources re-ranked
        from 1, suitable as one query's reply in :class:`FakeSearch`.
    """
    by_rank = {s.rank: s for s in base.sources}
    kept = [
        replace(by_rank[r], rank=i)
        for i, r in enumerate((r for r in ranks if r in by_rank), start=1)
    ]
    return GroundedSearchResult(
        answer=base.answer if answer is None else answer,
        sources=kept,
        related_questions=list(base.related_questions),
        prompt_tokens=base.prompt_tokens,
        completion_tokens=base.completion_tokens,
    )


