# FakeSearch
# --------------------------------------------------------------------------- #


class FakeSearch:
    """Replay canned :class:`GroundedSearchResult`(s) for the graph's queries.

    Each :meth:`search` call returns a deep copy so a node that mutates the
    result in place cannot poison later queries.

    Two modes:

    * Single result (``FakeSearch(result)``): every query gets the same reply
      -- the right shape for single-query scenarios.
    * Multiple results (``FakeSearch(results=[r1, r2, ...])``): replies are
      served round-robin across calls (thread-safe, since the search node runs
      queries in a ``ThreadPoolExecutor``). With N distinct results and N
      planned queries each query gets a different reply, so the Evidence Ledger
      genuinely COMBINES distinct per-query evidence (cross-query consolidation,
      signature-dedup, cross-checking across domains from different queries) --
      the multi-query case a single fixed reply cannot exercise. The assignment
      of which reply goes to which query is order-based and not asserted; only
      that distinct replies combine.
    """

    def __init__(
        self,
        result: GroundedSearchResult | None = None,
        *,
        results: Sequence[GroundedSearchResult] | None = None,
    ) -> None:
        """Bind the canned reply (single) or replies (round-robin) to serve.

        Args:
            result: Single reply returned for every query (back-compatible
                single-query mode). Mutually exclusive with *results*.
            results: Ordered replies served round-robin across :meth:`search`
                calls for multi-query combination scenarios.
        """
        if results is not None:
            self._results = list(results)
        elif result is not None:
            self._results = [result]
        else:
            self._results = [GroundedSearchResult()]
        self._lock = threading.Lock()
        self._call_index = 0

    def search(self, query: str, **kwargs: Any) -> GroundedSearchResult:
        """Return a deep copy of the next canned reply (round-robin)."""
        with self._lock:
            result = self._results[self._call_index % len(self._results)]
            self._call_index += 1
        return copy.deepcopy(result)

    def is_available(self) -> bool:
        """Report the fake as configured and ready."""
        return True

    @property
    def search_model(self) -> str:
        """Operator-facing identifier for the fake search backend."""
        return "fake-search"


