import { renderToStaticMarkup } from 'react-dom/server'
import { describe, expect, it } from 'vitest'

import { LocaleProvider } from '@/i18n/LocaleProvider'
import { ComposerDisclosureHint } from './ComposerDisclosureHint'

function markup(locale: 'de' | 'en' = 'de') {
  return renderToStaticMarkup(
    <LocaleProvider initialLocale={locale}>
      <ComposerDisclosureHint />
    </LocaleProvider>,
  )
}

describe('ComposerDisclosureHint', () => {
  it('states that answers come from an AI system and asks to verify them, in both languages', () => {
    expect(markup('de')).toContain('Antworten werden von einem KI-System erzeugt. Bitte überprüfen Sie die Angaben.')
    expect(markup('en')).toContain('Answers are generated by an AI system. Please verify the information.')
  })

  it('uses the helper-text role, not the smaller micro role', () => {
    // t-hint sits one step below the context meter beside it, which would
    // read as fine print — the exact thing the disclosure must not be.
    const html = markup()

    expect(html).toContain('t-meta')
    expect(html).not.toContain('t-hint')
  })

  it('keeps the colour token at full opacity', () => {
    // Informative text keeps its colour token at full opacity so it stays
    // readable; a disclosure must not be quieter than the controls around it.
    expect(markup()).toContain('text-muted-foreground')
    expect(markup()).not.toMatch(/text-muted-foreground\/\d/)
  })
})
